-- Limpiar tablas previas
DROP TABLE IF EXISTS incidencia CASCADE;
DROP TABLE IF EXISTS asignacion_compra CASCADE;
DROP TABLE IF EXISTS dispositivo CASCADE;
DROP TABLE IF EXISTS servicio_tecnico CASCADE;
DROP TABLE IF EXISTS proveedor CASCADE;
DROP TABLE IF EXISTS usuario CASCADE;
DROP TABLE IF EXISTS centro CASCADE;

CREATE TABLE centro (
    id_centro       INTEGER PRIMARY KEY,
    tipo            VARCHAR(50) NOT NULL,
    nombre          VARCHAR(100) NOT NULL,
    direccion       VARCHAR(150),
    municipio       VARCHAR(100)
);

CREATE TABLE proveedor (
    id_proveedor    SERIAL PRIMARY KEY,
    nombre          VARCHAR(100) NOT NULL,
    direccion       VARCHAR(150),
    telefono        VARCHAR(20),
    email           VARCHAR(100)
);

CREATE TABLE servicio_tecnico (
    id_servicio_tecnico  SERIAL PRIMARY KEY,
    nombre               VARCHAR(100) NOT NULL,
    direccion            VARCHAR(150),
    telefono             VARCHAR(20),
    email                VARCHAR(100)
);

CREATE TABLE usuario (
    id_usuario      SERIAL PRIMARY KEY,
    dni             VARCHAR(9) UNIQUE NOT NULL,
    id_centro       INTEGER REFERENCES centro(id_centro),
    nombre          VARCHAR(50) NOT NULL,
    apellidos       VARCHAR(100) NOT NULL,
    email           VARCHAR(100),
    departamento    VARCHAR(100),
    rol             VARCHAR(20)NOT NULL,  -- ADMIN / DIRE / RESP
    passwd_hash     VARCHAR(256) NOT NULL
);

CREATE TABLE asignacion_compra (
    id_asignacion    SERIAL PRIMARY KEY,
    id_centro        INTEGER REFERENCES centro(id_centro),
    id_proveedor     INTEGER REFERENCES proveedor(id_proveedor),
    entrega          DATE
);

CREATE TABLE dispositivo (
    id_dispositivo       INTEGER PRIMARY KEY,
    id_centro            INTEGER REFERENCES centro(id_centro),
    nombre               VARCHAR(100),
    num_serie            VARCHAR(100),
    marca_modelo         VARCHAR(100),
    ultima_actualizacion DATE,
    observaciones        VARCHAR(255),
    categoria            VARCHAR(50),
    estado               VARCHAR(50),
    uso                  VARCHAR(50),
    ubicacion            VARCHAR(100),
    id_asignacion        INTEGER REFERENCES asignacion_compra(id_asignacion)
);

CREATE TABLE incidencia (
    id_incidencia        SERIAL PRIMARY KEY,
    id_centro            INTEGER REFERENCES centro(id_centro),
    id_dispositivo       INTEGER REFERENCES dispositivo(id_dispositivo),
    id_servicio_tecnico  INTEGER REFERENCES servicio_tecnico(id_servicio_tecnico),
    dni_responsable      VARCHAR(9) REFERENCES usuario(dni),
    descripcion          VARCHAR(255),
    fecha_reporte        DATE DEFAULT NOW(),
    fecha_cierre         DATE,
    estado               VARCHAR(100) NOT NULL -- Averiado / En Servicio Técnico / Reparado / Faltan consumibles
);

